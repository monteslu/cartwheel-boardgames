// Checks the balance of First Hearth's cards and buildings (data/firsthearth-data.mjs) and writes src/firsthearth_data.h.
//
//   node tools/gen-data.mjs            check, then write the header
//   node tools/gen-data.mjs --check    check only (exit 1 on any failure)
//   node tools/gen-data.mjs --control  check a deliberately broken copy: it must fail (exit 0 when it does)
//
// The model, in points: one worker placement is worth about 3.5 points (a die averages 3.5 and every
// resource scores its own value per pip). A card costs a worker and 1 to 4 goods (2.5 on average, about 9
// points), so a card's immediate effect plus its expected end score must land in [CARD_MIN, CARD_MAX]. End
// expectations come from CPU-vs-CPU games (a typical village ends near field 4, tool strength 5, 4 buildings
// and 7 kin; a lore mark adds about 5 to its set). A building must score its cost's value, plus at most a
// small bonus, so it is never a trap and never a windfall.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as D from '../data/firsthearth-data.mjs';

const CARD_MIN = 9, CARD_MAX = 15;
const WORTH = { food: 1.5, wood: 2.7, clay: 3.6, stone: 4.5, gold: 5.4, points: 1, field: 5, tool: 3 };
const ROLE_END = [4, 5, 4, 7]; // field level, tool strength, buildings, kin at the end of a typical game
const MARK_END = 5;
const SUPPLY = { wood: 28, clay: 18, stone: 12, gold: 10 };

export function check(data) {
  const errs = [];
  const cardValue = (c) => {
    let v = 0;
    for (const [k, n] of c.fx) {
      if (!(k in WORTH)) errs.push(`${c.name}: unknown effect ${k}`);
      v += WORTH[k] * n;
    }
    v += c.mark !== undefined ? MARK_END : ROLE_END[c.role] * c.mult;
    return v;
  };
  if (data.CARDS.length !== 32) errs.push(`32 cards expected, ${data.CARDS.length}`);
  const marks = new Array(8).fill(0);
  const roleSum = [0, 0, 0, 0], roleN = [0, 0, 0, 0];
  const rows = [];
  for (const c of data.CARDS) {
    if (c.fx.length > 2) errs.push(`${c.name}: at most two effects`);
    if ((c.mark === undefined) === (c.role === undefined)) errs.push(`${c.name}: a mark or a role, not both`);
    const v = cardValue(c);
    rows.push([c.name, v]);
    if (v < CARD_MIN || v > CARD_MAX) errs.push(`card ${c.name} worth ${v.toFixed(1)}, outside [${CARD_MIN}, ${CARD_MAX}]`);
    if (c.mark !== undefined) marks[c.mark]++;
    else { roleSum[c.role] += v; roleN[c.role]++; }
  }
  marks.forEach((n, i) => { if (n !== 2) errs.push(`mark ${data.MARKS[i]} on ${n} cards, 2 expected`); });
  const roleAvg = roleSum.map((s, i) => s / roleN[i]);
  const lo = Math.min(...roleAvg), hi = Math.max(...roleAvg);
  if (hi - lo > 1.5) errs.push(`kin roles unbalanced: averages ${roleAvg.map((x) => x.toFixed(2)).join(' ')}`);

  if (data.BUILDINGS.length !== 28) errs.push(`28 buildings expected, ${data.BUILDINGS.length}`);
  const need = [0, 0, 0, 0];
  for (const b of data.BUILDINGS) {
    const val = b.cost[0] * 3 + b.cost[1] * 4 + b.cost[2] * 5 + b.cost[3] * 6;
    const pts = data.buildingPoints(b);
    const n = b.cost.reduce((a, x) => a + x, 0);
    if (n < 3 || n > 4) errs.push(`${b.name}: 3 or 4 pieces, not ${n}`);
    if (pts - val < 0 || pts - val > 2) errs.push(`building ${b.name}: ${pts} points for ${val} of goods`);
    b.cost.forEach((x, i) => { need[i] += x; });
  }
  // in a 4-seat game 28 buildings are built at most: the supply must not run dry for a single kind before
  // a quarter of them are gone (each kind's demand per building below its supply per 7 buildings)
  ['wood', 'clay', 'stone', 'gold'].forEach((k, i) => {
    const perSeven = (need[i] / 28) * 7;
    if (perSeven > SUPPLY[k]) errs.push(`${k}: 7 buildings use ${perSeven.toFixed(1)}, supply ${SUPPLY[k]}`);
  });
  return { errs, rows, roleAvg };
}

function header(data) {
  const fxCode = { food: 0, wood: 1, clay: 2, stone: 3, gold: 4, points: 5, field: 6, tool: 7 };
  const L = [];
  L.push('/* generated by tools/gen-data.mjs from data/firsthearth-data.mjs: do not edit */');
  L.push('#ifndef FIRSTHEARTH_DATA_H');
  L.push('#define FIRSTHEARTH_DATA_H');
  L.push('#include <stdint.h>');
  L.push(`#define TR_NCARDS ${data.CARDS.length}`);
  L.push(`#define TR_NBUILD ${data.BUILDINGS.length}`);
  L.push('typedef struct tr_card_def { const char *name; int8_t mark, role, mult, fx[2][2]; } tr_card_def;');
  L.push('typedef struct tr_build_def { const char *name; int8_t cost[4]; int8_t points; } tr_build_def;');
  L.push('static const tr_card_def tr_cards[TR_NCARDS] = {');
  for (const c of data.CARDS) {
    const fx = [0, 1].map((i) => (c.fx[i] ? `{${fxCode[c.fx[i][0]]}, ${c.fx[i][1]}}` : '{-1, 0}'));
    L.push(`  {"${c.name}", ${c.mark ?? -1}, ${c.role ?? -1}, ${c.mult ?? 0}, {${fx.join(', ')}}},`);
  }
  L.push('};');
  L.push('static const tr_build_def tr_builds[TR_NBUILD] = {');
  for (const b of data.BUILDINGS) L.push(`  {"${b.name}", {${b.cost.join(', ')}}, ${data.buildingPoints(b)}},`);
  L.push('};');
  L.push(`static const char *const tr_mark_names[8] = {${data.MARKS.map((m) => `"${m}"`).join(', ')}};`);
  L.push(`static const char *const tr_role_names[4] = {${data.ROLES.map((m) => `"${m}"`).join(', ')}};`);
  L.push('#endif');
  return L.join('\n') + '\n';
}

const args = process.argv.slice(2);
if (args.includes('--control')) {
  // a windfall card and a trap building: the checker must catch both
  const bad = { ...D, CARDS: D.CARDS.map((c, i) => (i === 0 ? { ...c, fx: [['gold', 3]] } : c)),
    BUILDINGS: D.BUILDINGS.map((b, i) => (i === 0 ? { ...b, cost: [3, 3, 0, 0] } : b)),
    buildingPoints: (b) => (b.cost[0] === 3 ? 9 : D.buildingPoints(b)) };
  const { errs } = check(bad);
  const caught = errs.some((e) => e.startsWith('card ')) && errs.some((e) => e.startsWith('building '));
  console.log(caught ? 'control: the broken data fails, as it must' : 'control: the broken data PASSED');
  process.exit(caught ? 0 : 1);
}
const { errs, rows, roleAvg } = check(D);
const vals = rows.map((r) => r[1]);
console.log(`cards: worth ${Math.min(...vals).toFixed(1)}..${Math.max(...vals).toFixed(1)} (band ${CARD_MIN}..${CARD_MAX}); roles ${roleAvg.map((x) => x.toFixed(1)).join(' ')}`);
if (errs.length) { for (const e of errs) console.error('FAIL ' + e); process.exit(1); }
if (!args.includes('--check')) {
  const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'firsthearth_data.h');
  writeFileSync(out, header(D));
  console.log('wrote ' + out);
}
